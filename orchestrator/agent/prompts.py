from __future__ import annotations

from orchestrator.tools.enums import (
    DISCREPANCY_META,
    ROUNDING_META,
    SEVERITY_LABEL,
)


def _discrepancy_codes() -> str:
    rows = ["| Код | Значение | Критичность |", "|---|---|---|"]
    rows += [
        f"| {code.value} | {description} | {SEVERITY_LABEL[severity]} |"
        for code, (description, severity) in DISCREPANCY_META.items()
    ]
    return "\n".join(rows)


def _rounding_patterns() -> str:
    rows = ["| Код | Источник разницы | Что с этим делать |", "|---|---|---|"]
    rows += [
        f"| {code.value} | {source} | {action} |"
        for code, (source, action) in ROUNDING_META.items()
    ]
    return "\n".join(rows)


